// Embeds server/zeppelin-oracle-setup.sh into the app as a one-line install command
// (gzip + base64), so the user can paste it into an SSH session without needing GitHub.
// Run after editing the server script: node scripts/embed-server-script.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const script = readFileSync(join(root, 'server/zeppelin-oracle-setup.sh'));
const sha256 = createHash('sha256').update(script).digest('hex');
const b64 = gzipSync(script, { level: 9 }).toString('base64');
const file = 'zeppelin-oracle-setup.sh';
const command =
  `echo '${b64}' | base64 -d | gunzip > ${file} && ` +
  `echo '${sha256}  ${file}' | sha256sum -c --quiet && sudo bash ${file}`;

const out = `// GENERATED by scripts/embed-server-script.mjs from server/zeppelin-oracle-setup.sh. Do not edit.
export const SERVER_SCRIPT_SHA256 = '${sha256}';
export const SERVER_SCRIPT_GZ_B64 = '${b64}';
/** Paste into the SSH session on the Oracle server: writes the script, verifies it, runs it. */
export const INSTALL_COMMAND = \`${command}\`;
`;
writeFileSync(join(root, 'src/generated/serverScript.ts'), out);
console.log(`serverScript.ts: script ${script.length} B, command ${command.length} chars, sha256 ${sha256}`);
