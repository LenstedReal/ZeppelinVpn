export type Lang = 'tr' | 'en';

export function hasKey(key: string): key is StringKey {
  return Object.prototype.hasOwnProperty.call(tr, key);
}

export function translate(lang: Lang, key: StringKey, params?: Record<string, string | number>): string {
  let text: string = lang === 'en' ? en[key] : tr[key];
  if (params) {
    for (const name of Object.keys(params)) {
      text = text.split(`{${name}}`).join(String(params[name]));
    }
  }
  return text;
}
